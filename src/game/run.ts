export const ALL_EVENT_IDS: EventId[] = Object.keys(RANDOM_EVENTS) as EventId[];

export type NodeType = 'paper_submission' | 'battle1' | 'event' | 'battle2' | 'final_decision';

export interface RouteNode {
  index: number;
  type: NodeType;
  eventId?: EventId;
  status: 'locked' | 'available' | 'completed';
}

export interface PendingBattleModifiers {
  startingApDelta: number;
  startingHandDelta: number;
  opponentSuspicionDelta: number;
  startingCrossCheckCharges: number;
}

export interface BattleResult {
  nodeIndex: number;
  outcome: GameOutcome;
  playerHpAfter: number;
  rounds: number;
  stats: GameStats;
}

export interface RunState {
  characterId: 'male' | 'female';
  paperTypeId: PaperTypeId;
  hp: number;
  maxHp: number;
  deck: Partial<Record<CardId, number>>;
  claimPool: CardId[];
  currentNodeIndex: number;
  nodes: RouteNode[];
  encounteredEventIds: EventId[];
  pendingBattleModifiers: PendingBattleModifiers;
  battleResults: BattleResult[];
  eventHistory: { eventId: EventId; chosenOption: 0 | 1 }[];
  rewardHistory: { nodeIndex: number; cardId: CardId | null }[];
  startTime: number;
  finalResult: GameOutcome | null;
}

export function pickTwoEvents(rng: Rng): [EventId, EventId] {
  const shuffled = shuffle([...ALL_EVENT_IDS], rng);
  return [shuffled[0], shuffled[1]];
}

export function createRunState(characterId: 'male' | 'female', paperTypeId: PaperTypeId, rng: Rng = defaultRng): RunState {
  const paperType = PAPER_TYPES[paperTypeId];
  const [ev1, ev2] = pickTwoEvents(rng);

  const nodes: RouteNode[] = [
    { index: 0, type: 'paper_submission', status: 'completed' },
    { index: 1, type: 'battle1', status: 'available' },
    { index: 2, type: 'event', eventId: ev1, status: 'locked' },
    { index: 3, type: 'event', eventId: ev2, status: 'locked' },
    { index: 4, type: 'battle2', status: 'locked' },
    { index: 5, type: 'final_decision', status: 'locked' },
  ];

  const baseDeck: Partial<Record<CardId, number>> = { ...PLAYER_BASE_DECK };
  baseDeck[paperType.initialCard] = (baseDeck[paperType.initialCard] ?? 0) + 1;

  const claimPool: CardId[] = [...BASIC_CLAIM_POOL, paperType.initialCard];

  return {
    characterId,
    paperTypeId,
    hp: 5,
    maxHp: 5,
    deck: baseDeck,
    claimPool,
    currentNodeIndex: 1,
    nodes,
    encounteredEventIds: [],
    pendingBattleModifiers: {
      startingApDelta: 0,
      startingHandDelta: 0,
      opponentSuspicionDelta: 0,
      startingCrossCheckCharges: 0,
    },
    battleResults: [],
    eventHistory: [],
    rewardHistory: [],
    startTime: Date.now(),
    finalResult: null,
  };
}

export function addCardToRun(run: RunState, cardId: CardId): RunState {
  const newDeck = { ...run.deck };
  newDeck[cardId] = (newDeck[cardId] ?? 0) + 1;
  const newPool = run.claimPool.includes(cardId) ? run.claimPool : [...run.claimPool, cardId];
  return { ...run, deck: newDeck, claimPool: newPool };
}

export function pickRandomAdvancedCard(rng: Rng): CardId {
  const idx = Math.floor(rng() * ADVANCED_CARD_IDS.length);
  return ADVANCED_CARD_IDS[idx];
}

export function pickThreeRewardCards(rng: Rng): [CardId, CardId, CardId] {
  const shuffled = shuffle([...ADVANCED_CARD_IDS], rng);
  return [shuffled[0], shuffled[1], shuffled[2]];
}

export function applyEventEffect(run: RunState, effect: EventEffect, rng: Rng): { run: RunState; pendingChoose?: true } {
  switch (effect.kind) {
    case 'heal': {
      const newHp = Math.min(run.maxHp, run.hp + effect.amount);
      return { run: { ...run, hp: newHp } };
    }
    case 'lose_hp': {
      const newHp = Math.max(1, run.hp - effect.amount);
      return { run: { ...run, hp: newHp } };
    }
    case 'add_card': {
      return { run: addCardToRun(run, effect.cardId) };
    }
    case 'add_random_advanced_card': {
      const cardId = pickRandomAdvancedCard(rng);
      return { run: addCardToRun(run, cardId) };
    }
    case 'choose_advanced_card': {
      return { run, pendingChoose: true };
    }
    case 'modify_next_battle_ap': {
      const mods = {
        ...run.pendingBattleModifiers,
        startingApDelta: run.pendingBattleModifiers.startingApDelta + effect.delta,
      };
      return { run: { ...run, pendingBattleModifiers: mods } };
    }
    case 'modify_next_battle_hand': {
      const mods = {
        ...run.pendingBattleModifiers,
        startingHandDelta: run.pendingBattleModifiers.startingHandDelta + effect.delta,
      };
      return { run: { ...run, pendingBattleModifiers: mods } };
    }
    case 'modify_opponent_suspicion': {
      const mods = {
        ...run.pendingBattleModifiers,
        opponentSuspicionDelta: run.pendingBattleModifiers.opponentSuspicionDelta + effect.delta,
      };
      return { run: { ...run, pendingBattleModifiers: mods } };
    }
    case 'grant_cross_check_charges': {
      const mods = {
        ...run.pendingBattleModifiers,
        startingCrossCheckCharges: run.pendingBattleModifiers.startingCrossCheckCharges + effect.count,
      };
      return { run: { ...run, pendingBattleModifiers: mods } };
    }
    case 'sequence': {
      let cur = run;
      let pendingChoose: true | undefined;
      for (const eff of effect.effects) {
        const r = applyEventEffect(cur, eff, rng);
        cur = r.run;
        if (r.pendingChoose) pendingChoose = true;
      }
      return { run: cur, pendingChoose };
    }
  }
}

export function advanceNode(run: RunState): RunState {
  const next = run.currentNodeIndex + 1;
  const nodes = run.nodes.map((n) => {
    if (n.index === next) return { ...n, status: 'available' as const };
    return n;
  });
  return { ...run, currentNodeIndex: next, nodes };
}

export function completeNode(run: RunState, nodeIndex: number): RunState {
  const nodes = run.nodes.map((n) => {
    if (n.index === nodeIndex) return { ...n, status: 'completed' as const };
    if (n.index === nodeIndex + 1) return { ...n, status: 'available' as const };
    return n;
  });
  return { ...run, nodes };
}

export interface RenderOptions {
  playerHp: number;
  playerMaxHp: number;
  deck: Partial<Record<CardId, number>>;
  claimPool: CardId[];
  pendingBattleModifiers: PendingBattleModifiers;
}

export function toRenderOptions(run: RunState): RenderOptions {
  return {
    playerHp: run.hp,
    playerMaxHp: run.maxHp,
    deck: run.deck,
    claimPool: run.claimPool,
    pendingBattleModifiers: run.pendingBattleModifiers,
  };
}

export interface BattleEndInfo {
  outcome: GameOutcome;
  playerHp: number;
  rounds: number;
  stats: GameStats;
}

export interface BattleEndResult {
  run: RunState;
  screen: 'reward' | 'summary';
}

export function resolveBattleEnd(run: RunState, info: BattleEndInfo): BattleEndResult {
  const nodeIndex = run.currentNodeIndex;
  const isFinal = run.nodes[nodeIndex]?.type === 'battle2';

  let next: RunState = {
    ...run,
    hp: Math.max(0, info.playerHp),
    battleResults: [
      ...run.battleResults,
      {
        nodeIndex,
        outcome: info.outcome,
        playerHpAfter: info.playerHp,
        rounds: info.rounds,
        stats: info.stats,
      },
    ],
  };
  next = clearBattleModifiers(next);

  if (info.outcome === 'reject') {
    return { run: { ...next, finalResult: 'reject' }, screen: 'summary' };
  }
  if (isFinal) {
    return { run: { ...next, finalResult: info.outcome }, screen: 'summary' };
  }

  const healed = Math.min(2, next.maxHp - next.hp);
  return { run: { ...next, hp: next.hp + healed }, screen: 'reward' };
}

export function finishBattleNode(run: RunState): RunState {
  return advanceNode(completeNode(run, run.currentNodeIndex));
}

export function finishRewardStep(run: RunState, cardId: CardId | null): RunState {
  const withCard = cardId ? addCardToRun(run, cardId) : run;
  const recorded: RunState = {
    ...withCard,
    rewardHistory: [...withCard.rewardHistory, { nodeIndex: run.currentNodeIndex, cardId }],
  };
  return finishBattleNode(recorded);
}

export function clearBattleModifiers(run: RunState): RunState {
  return {
    ...run,
    pendingBattleModifiers: {
      startingApDelta: 0,
      startingHandDelta: 0,
      opponentSuspicionDelta: 0,
      startingCrossCheckCharges: 0,
    },
  };
}
